import mongoose from "mongoose";

const { Schema } = mongoose;

// Part A (NLP sentiment benchmark) — one document per model architecture's final result.
export const NlpModel = mongoose.model(
  "NlpModel",
  new Schema({
    name: { type: String, required: true },
    accuracy: { type: Number, required: true },
    f1_weighted: { type: Number, required: true },
    category: { type: String, enum: ["classical", "deep_learning", "transformer"], required: true },
  })
);

// Part B (DRL trading agents) — one document per agent's final test-period backtest.
export const RlModel = mongoose.model(
  "RlModel",
  new Schema({
    agent: { type: String, required: true },
    variant: { type: String, default: "sentiment" },
    test_return_pct: Number,
    test_sharpe: Number,
    test_max_drawdown_pct: Number,
    beat_buy_and_hold: Boolean,
    status: { type: String, enum: ["pending", "complete"], default: "pending" },
    portfolio_curve: [Number],       // normalized portfolio value series, for charting
    buy_hold_curve: [Number],
    updatedAt: { type: Date, default: Date.now },
  })
);

// Log of live sentiment-demo predictions made through the dashboard.
export const PredictionLog = mongoose.model(
  "PredictionLog",
  new Schema({
    text: { type: String, required: true },
    label: { type: String, required: true },
    confidence: { type: Number, required: true },
    probabilities: { type: Schema.Types.Mixed },
    createdAt: { type: Date, default: Date.now },
  })
);

// Real news headlines fetched via yfinance + scored individually with FinBERT-LoRA.
export const NewsHeadline = mongoose.model(
  "NewsHeadline",
  new Schema({
    ticker: { type: String, required: true },
    headline: { type: String, required: true },
    date: { type: String, required: true },
    url: String,
    sentiment_score: { type: Number, required: true },
    sentiment_label: { type: String, enum: ["positive", "neutral", "negative"], required: true },
  })
);

// The full day-by-day A2C strategy replay (one document holding the whole timeline) --
// generated by scripts/generate_a2c_strategy.py from the actual saved model, not simulated.
export const A2CStrategy = mongoose.model(
  "A2CStrategy",
  new Schema({
    agent: { type: String, default: "A2C" },
    tickers: [String],
    initial_cash: Number,
    days: { type: Schema.Types.Mixed },   // array of {date, portfolio_value, cash, stocks: {ticker: {...}}}
    buy_hold_curve: [Number],
  })
);
